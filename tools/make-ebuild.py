#!/usr/bin/env python3
"""Turn Gentoo's www-client/firefox ebuild into www-client/posterfox.

    tools/make-ebuild.py --gentoo /var/db/repos/gentoo/www-client/firefox --version 158.0 \
                         --out <posterchanai>/os/overlay/www-client/posterfox [--rev 1]

PosterFox is Firefox built the way Gentoo builds it, plus: PosterFox branding, telemetry compiled OUT (USE=telemetry
does not exist any more), the PosterChan distribution (policies, prefs, autoconfig, uBlock Origin, the cyberpunk
theme), and profiles kept where Firefox keeps them so nothing is lost switching from firefox-bin.

WHY A GENERATOR AND NOT A FORK OF THE EBUILD: Gentoo's maintainers update firefox.ebuild for every Mozilla release
(new toolchain pins, patchsets, configure flags). A hand-copied ebuild drifts from that within weeks. This script
re-derives ours from theirs on every release with a short list of EXACT edits; when Gentoo changes a line one of
them depends on, it stops with the edit that no longer applies instead of producing a quietly wrong ebuild. That
is the whole maintenance surface -- see docs/MAINTAINING.md.
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
PINS = json.loads((HERE / "pins.json").read_text())


class EditFailed(SystemExit):
    pass


def sub(text: str, old: str, new: str, count: int = 1, what: str = "") -> str:
    n = text.count(old)
    if n != count:
        raise EditFailed(f"edit '{what or old[:60]}': expected {count} occurrence(s) of {old!r}, found {n} -- "
                         "Gentoo changed this line; update tools/make-ebuild.py")
    return text.replace(old, new)


def resub(text: str, pattern: str, new: str, what: str, count: int = 1) -> str:
    out, n = re.subn(pattern, new, text, flags=re.M)
    if n != count:
        raise EditFailed(f"edit '{what}': pattern {pattern!r} matched {n} time(s), expected {count}")
    return out


HELPERS = r'''

# ---------------------------------------------------------------------------------------- PosterFox
# Generated by posterfox/tools/make-ebuild.py from Gentoo's firefox ebuild. Do not edit by hand: change
# the generator (or the files under files/posterfox/) and regenerate.

posterfox_branding() {
	local b="${S}/browser/branding/posterfox"
	# Start from Mozilla's unofficial branding (every file the build expects is there), then lay ours over it.
	cp -r "${S}/browser/branding/unofficial" "${b}" || die "copying the unofficial branding failed"
	cp -r "${FILESDIR}/posterfox/branding/." "${b}/" || die "copying the PosterFox branding failed"
	# Keep profiles where firefox(-bin) keeps them (~/.mozilla/firefox), so switching loses no passwords, history or
	# bookmarks. MOZ_APP_PROFILE accepts only an IMPLIED value (a mozconfig setting is refused at configure).
	echo 'imply_option("MOZ_APP_PROFILE", "mozilla/firefox")' >> "${S}/browser/moz.configure" || die
}

posterfox_distribution() {
	# Ours REPLACES Gentoo's distribution.ini (installed just before this runs).
	insinto "${MOZILLA_FIVE_HOME}/distribution"
	newins "${FILESDIR}/posterfox/distribution/distribution.ini" distribution.ini
	doins "${FILESDIR}/posterfox/distribution/policies.json"

	# uBlock Origin is signed by addons.mozilla.org; policies.json force-installs it from here into every profile.
	insinto "${MOZILLA_FIVE_HOME}/distribution/extensions"
	newins "${DISTDIR}/posterfox-ublock0-${POSTERFOX_UBO}.xpi" uBlock0@raymondhill.net.xpi
	newins "${DISTDIR}/posterfox-privacybadger-${POSTERFOX_PB}.xpi" jid1-MnnxcxisBPnSXQ@jetpack.xpi
	# PosterChan's own add-ons live in the APPLICATION scope, unsigned (this build allows app,system), so they
	# update with the browser and need no addons.mozilla.org round trip.
	insinto "${MOZILLA_FIVE_HOME}/browser/extensions"
	newins "${FILESDIR}/posterfox/extensions/posterchan-cyberpunk.xpi" cyberpunk-theme@poster.place.xpi
	newins "${FILESDIR}/posterfox/extensions/posterfox-tab-containers.xpi" tab-containers@posterfox.poster.place.xpi

	# Default prefs, and the autoconfig hook that reads this computer's PosterChan instance and loads the
	# window chrome (posterfox.cfg -- it runs with chrome privileges, so it is installed read-only, root-owned).
	insinto "${MOZILLA_FIVE_HOME}/browser/defaults/preferences"
	doins "${FILESDIR}/posterfox/distribution/posterfox-prefs.js"
	insinto "${MOZILLA_FIVE_HOME}/defaults/pref"
	doins "${FILESDIR}/posterfox/distribution/autoconfig.js"
	insinto "${MOZILLA_FIVE_HOME}"
	doins "${FILESDIR}/posterfox/distribution/posterfox.cfg"
	insinto "${MOZILLA_FIVE_HOME}/posterchan"
	doins "${FILESDIR}/posterfox/distribution/posterfox-chrome.css"
	insinto "${MOZILLA_FIVE_HOME}/posterchan/xdg/gtk-3.0"
	doins "${FILESDIR}/posterfox/distribution/xdg/gtk-3.0/settings.ini"
}
'''


def transform(src: str, rev: int) -> str:
    t = src
    t = sub(t, 'MOZ_ESR=\n', f'MOZ_ESR=\n\n# PosterFox pins (posterfox/pins.json)\nPOSTERFOX_UBO="{PINS["ublock_origin"]}"\n'
            f'POSTERFOX_PB="{PINS["privacy_badger"]}"\nPOSTERFOX_PB_AMO="{PINS["privacy_badger_amo_file"]}"\n',
            what="pins after MOZ_ESR")
    t = sub(t, 'MOZ_PN="${PN%-bin}"', 'MOZ_PN="firefox"', what="MOZ_PN")
    t = resub(t, r'^DESCRIPTION=".*"$', 'DESCRIPTION="PosterFox: Firefox for PosterChanOS -- PosterChan look, uBlock Origin, no telemetry"',
              "DESCRIPTION")
    t = sub(t, '\t${PATCH_URIS[@]}\n',
            '\t${PATCH_URIS[@]}\n\thttps://github.com/gorhill/uBlock/releases/download/${POSTERFOX_UBO}/uBlock0_${POSTERFOX_UBO}.firefox.signed.xpi -> posterfox-ublock0-${POSTERFOX_UBO}.xpi\n'
            '\thttps://addons.mozilla.org/firefox/downloads/file/${POSTERFOX_PB_AMO}/privacy_badger17-${POSTERFOX_PB}.xpi -> posterfox-privacybadger-${POSTERFOX_PB}.xpi\n',
            what="SRC_URI uBlock")
    t = sub(t, 'S="${WORKDIR}/${PN}-${PV%_*}"', 'S="${WORKDIR}/${MOZ_PN}-${PV%_*}"', what="S")
    # PosterChanOS runs stable: a system library newer than its tree has is replaced by Firefox's bundled copy.
    for flag in PINS.get("bundled_libs", []):
        t = resub(t, r'^(IUSE\+?=".*?)\+' + re.escape(flag) + r'\b', r'\1' + flag, f"bundled {flag}")
    # Telemetry is not a choice in PosterFox: the flag goes, and every `use telemetry` reads false.
    t = resub(t, r'^(IUSE\+?=".*?) \+telemetry(.*")$', r'\1\2', "IUSE telemetry")
    t = resub(t, r'\buse telemetry\b', 'false', "use telemetry", count=len(re.findall(r'\buse telemetry\b', t)) or 1)
    # Our xpi is not a language pack: keep src_unpack from copying it into language_packs/.
    t = sub(t, '\t\tif [[ ${_src_file} == *.xpi ]]; then\n',
            '\t\tif [[ ${_src_file} == posterfox-* ]]; then\n\t\t\tcontinue\n\t\telif [[ ${_src_file} == *.xpi ]]; then\n',
            what="src_unpack skip")
    t = sub(t, '\teapply_user\n', '\teapply_user\n\n\tposterfox_branding\n', what="src_prepare branding")
    t = sub(t, '\t\t--enable-official-branding \\\n',
            '\t\t--with-branding=browser/branding/posterfox \\\n'
            '\t\t--with-app-name=posterfox \\\n'
            '\t\t--with-app-basename=PosterFox \\\n',
            what="branding configure flags")
    # Keep profiles where firefox(-bin) keeps them: switching to PosterFox loses no passwords, history or bookmarks.
    t = sub(t, '\tnewins "${FILESDIR}"/distribution.ini distribution.ini\n',
            '\tnewins "${FILESDIR}"/distribution.ini distribution.ini\n\tposterfox_distribution\n',
            what="src_install distribution")
    t = sub(t, 'local icon_srcdir="${S}/browser/branding/official"', 'local icon_srcdir="${S}/browser/branding/posterfox"',
            what="icons")
    t = sub(t, 'local app_name="Mozilla ${MOZ_PN^}"', 'local app_name="PosterFox"', what="desktop name")
    # The desktop-entry TEMPLATE is Gentoo's (files/icon/firefox-r3.desktop, @NAME@/@EXEC@/@ICON@ filled in below); the
    # ebuild names it by ${PN}, which is posterfox here -- a file that does not exist (the r7 build died on it).
    t = resub(t, r'"\$\{FILESDIR\}/icon/\$\{PN\}-(r\d+\.desktop)"', r'"${FILESDIR}/icon/firefox-\1"', "desktop template")
    # PosterFox installs to its own paths, so it may sit beside a stock Firefox: no blockers. firefox-l10n puts its
    # language packs into /usr/lib64/firefox, which PosterFox never reads, so it is not pulled in either.
    t = sub(t, 'FF_ONLY_DEPEND="!www-client/firefox:0\n\t', 'FF_ONLY_DEPEND="', what="firefox:0 blocker")
    t = sub(t, '\tRDEPEND+=" !www-client/firefox:rapid\n\t\t\t\t~www-client/firefox-l10n-${PV}:0/esr"\n',
            '\t: # PosterFox: no blocker on stock Firefox, no language-pack package (it installs into lib64/firefox)\n', what="esr blockers")
    t = sub(t, '\tRDEPEND+=" !www-client/firefox:esr\n\t\t\t\t~www-client/firefox-l10n-${PV}:0/rapid"\n',
            '\t: # PosterFox: no blocker on stock Firefox, no language-pack package (it installs into lib64/firefox)\n', what="rapid blockers")
    t = sub(t, 'org.mozilla.firefox-symbolic.svg firefox-symbolic.svg\n',
            'org.mozilla.firefox-symbolic.svg posterfox-symbolic.svg\n', what="symbolic icon")
    t = resub(t, r'^\tdosym -r /usr/share/icons/hicolor/symbolic/apps/firefox-symbolic\.svg .*\n', '', "symbolic icon symlink")
    header = (f"# PosterFox {rev}: generated from www-client/firefox by posterfox/tools/make-ebuild.py.\n"
              "# Edit the generator, not this file.\n")
    return header + t + HELPERS


def wrapper(src: str) -> str:
    """Gentoo's /usr/bin/firefox launcher, pointed at /usr/lib*/posterfox/posterfox."""
    t = sub(src, 'MOZ_FIREFOX_FILE="firefox"', 'MOZ_FIREFOX_FILE="posterfox"', what="wrapper program")
    t = resub(t, r'(LIB_DIR\})/firefox\b', r'\1/posterfox', "wrapper lib dirs", count=5)
    # PosterChan windows have minimise/maximise/close on the right; GTK's default layout gives Firefox close only.
    # PosterFox's own GTK settings come first in XDG_CONFIG_DIRS (the user's ~/.config still wins).
    return sub(t, '# Run the browser\n',
               '# PosterFox: its own GTK settings first (window buttons like every PosterChan window)\n'
               'export XDG_CONFIG_DIRS="${MOZILLA_FIVE_HOME}/posterchan/xdg${XDG_CONFIG_DIRS:+:${XDG_CONFIG_DIRS}}"\n\n'
               '# Run the browser\n', what="wrapper gtk settings")


def newest_firefox(gentoo: pathlib.Path) -> str:
    """The newest NON-ESR firefox version in the Gentoo tree (the rapid release PosterFox follows)."""
    vs = []
    for e in gentoo.glob("firefox-*.ebuild"):
        v = e.name[len("firefox-"):-len(".ebuild")]
        if "esr" in v or "_" in v or "9999" in v:
            continue
        if re.fullmatch(r"\d+(\.\d+)*(-r\d+)?", v):
            vs.append(v)
    if not vs:
        raise SystemExit("no firefox ebuild found in " + str(gentoo))
    key = lambda v: [int(x) for x in re.split(r"[.\-r]+", v) if x.isdigit()]
    return max(vs, key=key)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gentoo", default="/var/db/repos/gentoo/www-client/firefox", type=pathlib.Path)
    ap.add_argument("--version", help="firefox ebuild version (PV[-rN]); default: the newest rapid release")
    ap.add_argument("--out", required=True, type=pathlib.Path, help="overlay package dir, e.g. os/overlay/www-client/posterfox")
    ap.add_argument("--rev", type=int, default=int((HERE / "REVISION").read_text().strip()))
    a = ap.parse_args(argv)
    ver = a.version or newest_firefox(a.gentoo)
    src = (a.gentoo / f"firefox-{ver}.ebuild").read_text()
    out = transform(src, a.rev)
    pv = ver.split("-r")[0]
    a.out.mkdir(parents=True, exist_ok=True)
    for old in a.out.glob("posterfox-*.ebuild"):
        old.unlink()
    target = a.out / f"posterfox-{pv}-r{a.rev}.ebuild"
    target.write_text(out)
    r = subprocess.run(["bash", "-n", str(target)], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("generated ebuild is not valid bash:\n" + r.stderr)
    # Gentoo's files/ (desktop template, prefs, patches) + ours, side by side.
    files = a.out / "files"
    if files.exists():
        shutil.rmtree(files)
    shutil.copytree(a.gentoo / "files", files)
    shutil.copytree(HERE / "build" / "files-posterfox", files / "posterfox")
    (files / "posterfox-r1.sh").write_text(wrapper((a.gentoo / "files" / "firefox-r1.sh").read_text()))
    meta = a.gentoo / "metadata.xml"
    if meta.exists():
        (a.out / "metadata.xml").write_text(meta.read_text())
    print(target)


if __name__ == "__main__":
    sys.exit(main())
